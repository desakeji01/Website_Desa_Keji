export function isTahunDesaCantik(
  value: number,
): value is TahunDesaCantik {
  return TAHUN_DESA_CANTIK.includes(
    value as TahunDesaCantik,
  );
}

export function getKategoriDesaCantik(slug: string) {
  return KATEGORI_DESA_CANTIK.find(
    (kategori) => kategori.slug === slug,
  );
}

export function isKategoriDesaCantik(
  slug: string,
): slug is KategoriDesaCantik {
  return Boolean(getKategoriDesaCantik(slug));
}

export function getDataPenduduk(
  kategori: KategoriDesaCantik,
  tahun: TahunDesaCantik,
) {
  if (kategori === 'penduduk' && tahun === 2025) {
    return DATA_PENDUDUK_2025;
  }

  return [];
}

export function hitungRingkasanPenduduk(
  rows: PendudukKelompokUmur[],
) {
  return rows.reduce(
    (ringkasan, row) => ({
      lakiLaki:
        ringkasan.lakiLaki + row.total.lakiLaki,
      perempuan:
        ringkasan.perempuan + row.total.perempuan,
      jumlah:
        ringkasan.jumlah + row.total.jumlah,
    }),
    {
      lakiLaki: 0,
      perempuan: 0,
      jumlah: 0,
    },
  );
}

